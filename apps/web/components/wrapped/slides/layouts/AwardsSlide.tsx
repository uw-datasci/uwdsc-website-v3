interface AwardsSlideProps {
  readonly slide: AwardsSlideData;
}

/**
 * "Awards" slide: three full-height colored columns of different heights,
 * each topped with a hand-drawn doodle and a title plus percentile line at
 * the top of the column
 *
 * Data injection points (see {@link AwardsSlideData}):
 * - `slide.awards`: exactly 3 entries. `awards[0]` renders in the tallest
 *   center column, `awards[1]` in the left column, `awards[2]` in the right
 *   column. Each entry's `title` and `topPercent` render as the two caption
 *   lines.
 *
 * Not driven by data: column heights and colors live in the `columns` array
 * below (`heightPct`/`color`). The doodle SVGs (`CherryDoodle`, `BirdDoodle`,
 * `PetalDoodle`) are hardcoded, edit their `fill` values to recolor them or
 * swap in a different `Icon` component to change the artwork. There's no
 * heading on this slide, matching the Figma reference.
 */
export function AwardsSlide({ slide }: AwardsSlideProps) {
  const [center, left, right] = slide.awards;

  const columns = [
    { award: left, heightPct: 42.3, color: "#ffca82", Icon: CherryDoodle, iconWidthPct: 71, iconRotate: "-19.34deg" },
    { award: center, heightPct: 71.5, color: "#ff8f64", Icon: BirdDoodle, iconWidthPct: 79, iconRotate: "-12.81deg" },
    { award: right, heightPct: 52.9, color: "#9cd8ea", Icon: PetalDoodle, iconWidthPct: 55, iconRotate: "0deg" },
  ] as const;

  return (
    <div
      className={cn(
        "flex h-full w-full items-end overflow-hidden bg-[#ff7075] text-black",
        tiltWarp.variable,
        atkinsonHyperlegibleMono.variable,
      )}
    >
      {columns.map((column, index) =>
        column.award ? (
          <div key={column.award.id} className="flex h-full flex-1 flex-col items-center justify-end">
            <div className="mb-2" style={{ width: `${column.iconWidthPct}%`, transform: `rotate(${column.iconRotate})` }}>
              <column.Icon />
            </div>
            <div
              className="flex w-full flex-col items-center gap-0.5 pt-3"
              style={{ height: `${column.heightPct}%`, backgroundColor: column.color }}
            >
              <p className={cn(mono, "text-center text-[0.625rem] leading-tight text-black")}>{column.award.title}</p>
              <p className={cn(display, "text-center text-[0.9375rem] leading-none text-black")}>
                {column.award.topPercent}
              </p>
            </div>
          </div>
        ) : (
          <div key={index} className="h-full flex-1" />
        ),
      )}
    </div>
  );
}

